export type 期望<T extends true> = T
export type 等于<X, Y> = (<T>() => T extends X ? 1 : 2) extends <T>() => T extends Y ? 1 : 2 ? true : false

// ============================================================================
// 准备测试用的高阶类型
// ============================================================================

interface 数组高阶类型 extends HktType {
  参数长度: 1
  结果: Array<this['参数'][0]>
}

interface 字典高阶类型 extends HktType {
  参数长度: 2
  结果: Record<this['参数'][0] extends PropertyKey ? this['参数'][0] : never, this['参数'][1]>
}

interface 元组拼接高阶类型 extends HktType {
  参数长度: 3
  结果: [this['参数'][0], this['参数'][1], this['参数'][2]]
}

interface 无参数高阶类型 extends HktType {
  参数长度: 0
  结果: '固定结果'
}

